import { cookies } from "next/headers";
import type { RequestOptions } from "./http";

/**
 * Опции запроса для вызовов из серверного рантайма.
 *
 * Серверный рендер не имеет к кукам браузера автоматического доступа: axios на
 * сервере — это обычный HTTP-клиент, никакого «текущего пользователя» у него
 * нет. Заголовок `Cookie` собирается из входящего запроса и прикладывается
 * руками — иначе после фазы 2.2 сервер ходил бы в API анонимно и получал 401
 * там, где браузер получает данные.
 *
 * Модуль импортирует `next/headers`, то есть существует только на сервере.
 * Клиентский компонент, попытавшийся его подключить, не соберётся — это и есть
 * защита от случайного использования не на той стороне.
 */
export const getServerRequestOptions = async (): Promise<RequestOptions> => {
  const cookieHeader = (await cookies()).toString();

  return cookieHeader ? { headers: { Cookie: cookieHeader } } : {};
};
