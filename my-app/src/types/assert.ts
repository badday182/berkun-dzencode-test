/**
 * Проверка исчерпывающего разбора размеченного объединения.
 *
 * Если в `switch` забыть ветку, аргумент перестанет быть `never`
 * и код не скомпилируется — ошибка ловится на сборке, а не в рантайме.
 */
export const assertNever = (value: never): never => {
  throw new Error(`Необработанный вариант: ${JSON.stringify(value)}`);
};
